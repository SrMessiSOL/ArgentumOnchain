import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import ts from 'typescript';
const require=createRequire(import.meta.url),module={exports:{}};
const source=readFileSync(new URL('../lib/wallet-connection.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
new Function('module','exports','require',code)(module,module.exports,require);
const {resolveSigningWallet}=module.exports;
const wallet={address:'active'},counts={picker:0},choose=async()=>{counts.picker++;return wallet;};
assert.equal(await resolveSigningWallet({status:()=> 'connected',current:()=>wallet,wait:async()=>{},choose}),wallet);
assert.equal(counts.picker,0,'connected wallet skips picker');
let status='connecting';
assert.equal(await resolveSigningWallet({status:()=>status,current:()=>wallet,wait:async()=>{status='connected';},choose}),wallet);
assert.equal(counts.picker,0,'restoring wallet skips picker');
await assert.rejects(resolveSigningWallet({status:()=> 'connected',current:()=>null,wait:async()=>{},choose}),/wallet.unsupported/);
await assert.rejects(resolveSigningWallet({status:()=> 'connecting',current:()=>null,wait:async()=>{},choose}),/assets.pending/);
assert.equal(counts.picker,0,'connection failures do not reopen provider selection');
await resolveSigningWallet({status:()=> 'disconnected',current:()=>null,wait:async()=>{},choose});
await resolveSigningWallet({status:()=> 'connected',current:()=>wallet,wait:async()=>{},choose},true);
assert.equal(counts.picker,2,'only disconnected or explicit switching opens picker');
console.log('PASS: active, restoring, unsupported, timed-out, disconnected and explicit wallet selection.');
