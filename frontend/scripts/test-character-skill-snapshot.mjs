import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),ts=require('../../server/node_modules/typescript');
const source=fs.readFileSync(new URL('../../api/src/game-asset-policy.ts',import.meta.url),'utf8');
const exports={};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,require:name=>{if(name==='node:crypto')return crypto;if(name==='./db')return {default:{}};if(name==='./game-asset-chain')return {};throw Error(`Unexpected import: ${name}`);},Date,Set,JSON,Object});
const queries=[],client={query:async(sql,params)=>{queries.push([sql,params]);return {rows:[]};}};
const character={id:'test-character',name:'Tester',level:10,account_id:'private-account'};
const before=await exports.readBundle(client,character),after=await exports.readBundle(client,{...character,skill_state:null});
assert.equal(exports.bundleHash(before),exports.bundleHash(after),'nullable migration preserves existing hashes');
const withSkills=await exports.readBundle(client,{...character,skill_state:{version:1,navigation:25}});
assert.notEqual(exports.bundleHash(before),exports.bundleHash(withSkills),'skill changes are bound to the character snapshot');
assert.equal(withSkills.character.skill_state.navigation,25);
assert.equal(withSkills.character.account_id,undefined);
assert.equal(queries.length,15);assert.ok(queries.every(([,params])=>params[0]===character.id));
console.log('PASS: legacy snapshot hashes preserved; populated skills included in character settlement; no database/network calls.');
